"""Recognize a Mandarin WAV or microphone recording and send a Task 4 instruction."""

import argparse
import hashlib
from io import BytesIO
import json
from pathlib import Path
import subprocess
import sys
import tempfile
import time
from uuid import uuid4
import wave

from task4_bringup.result_io import atomic_write_json
from task4_bringup.task_cli import publish_task
from task4_bringup.task_parser import (
    default_config_paths,
    generate_task_id,
    load_yaml_config,
    parse_task,
)


SAMPLE_RATE = 16000
DEFAULT_MODEL = Path("models/weights/vosk-model-small-cn-0.22")


def recognize_wav(audio, model_path):
    """Return the Vosk transcript and the duration of the recognized recording."""
    with wave.open(BytesIO(audio), "rb") as stream:
        if (stream.getnchannels(), stream.getsampwidth(), stream.getframerate()) != (1, 2, SAMPLE_RATE):
            raise ValueError("录音须为 16 kHz、单声道、16 位 PCM WAV。")
        frame_count = stream.getnframes()
        if frame_count == 0:
            raise ValueError("录音不含音频帧。")

        if not model_path.is_dir():
            raise ValueError(f"找不到 Vosk 中文模型，检查 --model 指定的路径：{model_path}")
        try:
            from vosk import KaldiRecognizer, Model, SetLogLevel
        except ImportError as exc:
            raise RuntimeError("无法导入 Vosk，请按语音交接步骤加载项目内依赖。") from exc

        SetLogLevel(-1)
        model = Model(model_path=str(model_path))
        recognizer = KaldiRecognizer(model, SAMPLE_RATE)
        segments = []
        remaining = frame_count
        while remaining:
            data = stream.readframes(min(remaining, 4000))
            if not data or len(data) % 2:
                raise ValueError("WAV 音频数据不完整。")
            remaining -= len(data) // 2
            if recognizer.AcceptWaveform(data):
                segments.append(json.loads(recognizer.Result())["text"])
        segments.append(json.loads(recognizer.FinalResult())["text"])
        return " ".join(segment for segment in segments if segment), frame_count / SAMPLE_RATE


def record_wav(device, seconds):
    with tempfile.TemporaryDirectory(prefix="task4-voice-") as directory:
        path = Path(directory) / "recording.wav"
        print(f"开始录音（{seconds} 秒）。", file=sys.stderr)
        subprocess.run(
            ["arecord", "-q", "-D", device, "-t", "wav", "-f", "S16_LE", "-r", str(SAMPLE_RATE),
             "-c", "1", "-d", str(seconds), str(path)],
            check=True,
            timeout=seconds + 8,
        )
        return path.read_bytes()


def print_json(value):
    print(json.dumps(value, ensure_ascii=False, allow_nan=False))


def main(args=None):
    parser = argparse.ArgumentParser(description=__doc__)
    inputs = parser.add_mutually_exclusive_group(required=True)
    inputs.add_argument("--wav", type=Path, help="16 kHz mono PCM WAV file")
    inputs.add_argument("--record", action="store_true", help="Record once from the selected microphone")
    parser.add_argument("--synthetic", action="store_true", help="Label a WAV file generated by speech synthesis")
    parser.add_argument("--device", default="default", help="ALSA recording device")
    parser.add_argument("--seconds", type=int, default=4)
    parser.add_argument("--model", type=Path, default=DEFAULT_MODEL)
    parser.add_argument("--rooms", type=Path)
    parser.add_argument("--objects", type=Path)
    parser.add_argument("--topic", default="/task4/task")
    parser.add_argument("--results-dir", type=Path, default=Path("results/runs"))
    parser.add_argument("--dry-run", action="store_true", help="Recognize and parse without ROS publishing")
    options = parser.parse_args(args)
    if options.synthetic and options.record:
        parser.error("--synthetic requires --wav")
    if options.seconds < 1:
        parser.error("--seconds must be positive")

    try:
        audio = options.wav.read_bytes() if options.wav else record_wav(options.device, options.seconds)
        started = time.perf_counter()
        transcript, duration = recognize_wav(audio, options.model)
        recognition_sec = time.perf_counter() - started
    except (OSError, EOFError, ValueError, RuntimeError, subprocess.SubprocessError, wave.Error) as exc:
        print_json({"ok": False, "error": "voice_input_failed", "message": str(exc)})
        return 1

    rooms_path, objects_path = default_config_paths()
    result = parse_task(
        "".join(transcript.split()),
        load_yaml_config(options.rooms or rooms_path),
        load_yaml_config(options.objects or objects_path),
        source="voice",
        task_id=f"{generate_task_id()}-voice-{uuid4().hex[:8]}",
        require_enabled=True,
    )
    if not result["ok"]:
        print_json({**result, "transcript": transcript})
        return 1

    task = result["task"]
    voice_input = "synthetic_wav" if options.synthetic else "wav"
    if options.record:
        voice_input = "microphone"
    task["voice_input"] = voice_input
    if not options.dry_run:
        run_dir = options.results_dir / task["task_id"]
        try:
            run_dir.mkdir(parents=True, exist_ok=False)
            (run_dir / "voice.wav").write_bytes(audio)
            atomic_write_json(run_dir / "voice.json", {
                "task_id": task["task_id"],
                "input": voice_input,
                "model": options.model.name,
                "transcript": transcript,
                "duration_sec": duration,
                "recognition_sec": round(recognition_sec, 3),
                "audio_sha256": hashlib.sha256(audio).hexdigest(),
            })
        except OSError as exc:
            print_json({"ok": False, "error": "voice_save_failed", "message": str(exc)})
            return 1

        payload = json.dumps(task, ensure_ascii=False, allow_nan=False)
        publish_error = publish_task(payload, options.topic, node_name="task4_voice_task")
        if publish_error:
            print_json({"ok": False, "error": publish_error, "task_id": task["task_id"], "topic": options.topic})
            return 1

    print_json(task)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
